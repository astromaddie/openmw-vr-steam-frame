local source = assert(os.getenv('OPENMW_SOURCE'), 'OPENMW_SOURCE must point to OpenMW source')
package.path = source .. '/files/data/?.lua;' .. package.path

local values = {}
local settingsChanged
local actionHandlers = {}
local boundActions = {}
local triggerHandlers = {}
local messages = {}
local lookRight = 0
local pose = { position = { z = 0 } }
local self = { controls = { yawChange = 0, use = 0 } }

local controlsSection = {
    get = function(_, key) return values[key] end,
    set = function(_, key, value) values[key] = value end,
    subscribe = function(_, callback) settingsChanged = callback end,
}
local common = {
    controlsSection = controlsSection,
    l10nKey = 'VRInputLocalization',
    onFrame = function() end,
    setOnInputChangedBoolean = function() end,
    registerAutogeneratedSettingsGroup = function() end,
}

local vr = {
    isVr = function() return true end,
    _setPointerLeft = function() end,
    _setPointerRight = function() end,
    _pointerActivate = function() end,
    _setCurrentScroll = function() end,
    _frameSettingGet = function(key)
        assert(key == 'posture center')
        return 1
    end,
}
package.preload['openmw.vr'] = function() return vr end
package.preload['openmw.ui'] = function()
    return {
        _menuBack = function() end,
        showMessage = function(message) messages[#messages + 1] = message end,
    }
end
package.preload['openmw.util'] = function() return {} end
package.preload['openmw.interfaces'] = function()
    return {
        UI = { MODE = { VrMetaMenu = 'VrMetaMenu' }, getMode = function() end,
            addMode = function() end },
        vrspaces = {
            unitsPerMeter = 100,
            referenceSpaces = { View = 'View', Local = 'Local' },
            locateSpace = function() return pose end,
            recenterXY = function() end,
        },
        vrinputs = { isKBMouseMode = function() return false end },
        Controls = { overrideCombatControls = function() end },
    }
end
package.preload['openmw.storage'] = function()
    return { playerSection = function() return controlsSection end }
end
package.preload['openmw.input'] = function()
    return {
        registerTriggerHandler = function(key, callback) triggerHandlers[key] = callback end,
        registerActionHandler = function(key, callback) actionHandlers[key] = callback end,
        bindAction = function(key, callback) boundActions[key] = callback end,
        getBooleanActionValue = function() return false end,
        getRangeActionValue = function(key) return key == 'LookRight' and lookRight or 0 end,
    }
end
package.preload['openmw.core'] = function()
    return {
        isWorldPaused = function() return false end,
        l10n = function() return function(key) return key end end,
    }
end
package.preload['openmw.async'] = function()
    return { callback = function(_, callback) return callback end }
end
package.preload['openmw.types'] = function()
    local player = {
        CONTROL_SWITCH = { Controls = 1, Magic = 2, Fighting = 3 },
        getControlSwitch = function() return true end,
        isWerewolf = function() return false end,
        sendMenuEvent = function() end,
    }
    local actor = { STANCE = { Spell = 1, Weapon = 2, Nothing = 3 },
        getStance = function() return 3 end }
    return { Player = player, Actor = actor }
end
package.preload['openmw.self'] = function()
    return self
end
package.preload['scripts.omw.vr.inputs.common'] = function() return common end

local player = dofile(source .. '/files/data/scripts/omw/vr/inputs/player.lua')
local handlers = player.engineHandlers

local function expect(condition, message)
    if not condition then error(message, 2) end
end

expect(type(settingsChanged) == 'function', 'production player did not subscribe to control settings')
actionHandlers.SnapTurnRight(true)
expect(math.abs(self.controls.yawChange - math.rad(30)) < 1e-9,
    'empty storage did not use the 30 degree snap-turn fallback')
handlers.onVRFrame()
expect(boundActions.Sneak(0, false) == false,
    'empty storage unexpectedly enabled physical sneak')
expect(#messages == 0, 'empty storage unexpectedly enabled sneak messages')

-- Values arrive after startup when the settings group is registered. Refresh the
-- production player's live handlers and prove explicit values take precedence.
values.SmoothTurn = true
values.SmoothTurnSensitivity = 4
values.SnapTurnRate = 45
values.PhysicalSneak = true
values.PhysicalSneakMessage = true
values.PhysicalSneakOffset = 50
settingsChanged()

values.SmoothTurn = false
settingsChanged()
actionHandlers.SnapTurnRight(true)
expect(math.abs(self.controls.yawChange - math.rad(45)) < 1e-9,
    'saved snap-turn rate was not applied')
values.SmoothTurn = true
settingsChanged()

lookRight = 1
actionHandlers.LookRight(true)
handlers.onFrame(0.5)
expect(math.abs(self.controls.yawChange - 2) < 1e-9,
    'saved smooth-turn sensitivity was not applied to live player input')

pose.position.z = 60
handlers.onVRFrame()
expect(boundActions.Sneak(0, false) == false,
    'saved physical-sneak offset was not applied')
pose.position.z = 40
handlers.onVRFrame()
expect(boundActions.Sneak(0, false) == true,
    'saved physical-sneak setting or offset was not applied')
expect(#messages == 1, 'saved physical-sneak message setting was not applied')

values.SnapTurnRate = 'invalid'
values.SmoothTurnSensitivity = 0 / 0
values.PhysicalSneakOffset = math.huge
values.SmoothTurn = 1
values.PhysicalSneak = 'yes'
values.PhysicalSneakMessage = nil
settingsChanged()
actionHandlers.SnapTurnRight(true)
expect(math.abs(self.controls.yawChange - math.rad(30)) < 1e-9,
    'non-finite or wrongly typed settings were not replaced by safe defaults')

print('Production player settings startup tests passed')
